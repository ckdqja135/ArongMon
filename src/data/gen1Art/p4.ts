import { E, L, P, R, art, belly, eye, fluff, mouth, soft, spot, F, type MonArt } from '../monArtKit';

type Shape = MonArt['shapes'][number];
type Opt = Parameters<typeof E>[5];

/** 타원의 호 조각(도 단위, 현으로 닫힘). 180~360이 위쪽 절반 */
const arc = (cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, col: number, o: Opt = {}): Shape => {
  const pts: number[] = [];
  for (let i = 0; i <= 14; i++) {
    const a = ((a0 + ((a1 - a0) * i) / 14) * Math.PI) / 180;
    pts.push(cx + Math.cos(a) * rx, cy + Math.sin(a) * ry);
  }
  return P(pts, col, o);
};

/** 흰자 + 점 눈동자 */
const dotEye = (x: number, y: number, r = 2.4, p = 1): Shape[] => [
  E(x, y, r, r, 0, F),
  E(x, y, p, p, 3, { ...F, shade: false }),
];

/** 치켜뜬 눈 (dir 1 = 화면 왼쪽 눈, -1 = 오른쪽 눈) */
const slantEye = (x: number, y: number, dir: number, col = 0, s = 1): Shape[] => [
  P([x - 5 * s * dir, y - 3 * s, x + 4 * s * dir, y + 1 * s, x + 3 * s * dir, y + 4 * s, x - 4 * s * dir, y + 2.5 * s], col, F),
  E(x + 1.2 * s * dir, y + 1.6 * s, 1 * s, 1.2 * s, 3, { ...F, shade: false }),
];

/** 코일 한 마리 (k 배율, 자석은 좌/우 선택) */
const mite = (cx: number, cy: number, k: number, left = true, right = true): Shape[] => {
  const out: Shape[] = [];
  const mag = (d: number) => {
    const x = (v: number) => cx + d * v * k;
    const box = (x0: number, y0: number, x1: number, y1: number, col: number) =>
      out.push(P([x(x0), cy + y0 * k, x(x1), cy + y0 * k, x(x1), cy + y1 * k, x(x0), cy + y1 * k], col));
    box(9, -2, 17, 2, 2);
    box(15, -9, 20, 9, 2);
    box(19, -9, 26, -4, 2);
    box(19, 4, 26, 9, 2);
    box(23, -9, 26, -4, 4);
    box(23, 4, 26, 9, 5);
  };
  if (left) mag(-1);
  if (right) mag(1);
  out.push(
    R(cx - 1.5 * k, cy - 16 * k, 3 * k, 7 * k, 2), E(cx, cy - 16 * k, 4 * k, 2 * k, 2),
    E(cx - 6 * k, cy + 10.5 * k, 2.2 * k, 3 * k, 2), E(cx + 6 * k, cy + 10.5 * k, 2.2 * k, 3 * k, 2),
    E(cx, cy, 11 * k, 11 * k, 1),
    E(cx, cy, 5 * k, 5 * k, 0, F), E(cx, cy, 1.6 * k, 1.6 * k, 3, { ...F, shade: false }),
  );
  return out;
};

