/** 배의 소용돌이 무늬 (앞모습 전용) */
const swirl = (cx: number, cy: number, r: number, turns = 1.6): MonArt['shapes'] => {
  const out: MonArt['shapes'] = [];
  const n = 16;
  const pt = (i: number) => {
    const t = i / n;
    const a = t * turns * Math.PI * 2 + Math.PI / 2;
    return [cx + Math.cos(a) * r * t, cy + Math.sin(a) * r * t * 0.9];
  };
  for (let i = 0; i < n; i++) {
    const [x1, y1] = pt(i), [x2, y2] = pt(i + 1);
    out.push(L(x1, y1, x2, y2, 3, 1.3, FS));
  }
  return out;
};
/** 화난 눈썹 한 쌍 */
