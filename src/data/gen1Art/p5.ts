/** 반원(위쪽 또는 아래쪽) */
const dome = (cx: number, cy: number, rx: number, ry: number, col: number, lower: boolean, o: object = {}): Shape => {
  const pts: number[] = [];
  for (let i = 0; i <= 14; i++) {
    const a = (Math.PI * i) / 14;
    pts.push(cx + Math.cos(a) * rx, cy + Math.sin(a) * ry * (lower ? 1 : -1));
  }
  return P(pts, col, o);
};
/** 회전 가능한 n각 별 */
const starN = (cx: number, cy: number, r: number, col: number, n = 5, rot = 0, inner = 0.45, o: object = {}): Shape => {
  const pts: number[] = [];
  for (let i = 0; i < n * 2; i++) {
    const a = (i / (n * 2)) * Math.PI * 2 - Math.PI / 2 + rot;
    const rr = i % 2 ? r * inner : r;
    pts.push(cx + Math.cos(a) * rr, cy + Math.sin(a) * rr);
  }
  return P(pts, col, o);
};
