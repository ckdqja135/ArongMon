/** 실내 맵의 출구 (문 바로 아래 바깥 칸) */
export function exitOf(mapId: string): { map: string; x: number; y: number } | null {
  const d = doors.find(([, , , b]) => b === mapId);
  return d ? { map: d[0], x: d[1], y: d[2] + 1 } : null;
}
function doorWarps(id: string): Warp[] {
  const out: Warp[] = [];
  for (const [a, ax, ay, b, bx, by] of doors) {
    if (a === id) out.push({ x: ax, y: ay, to: b, tx: bx, ty: by, dir: 'up' });
    if (b === id) out.push({ x: bx, y: by, to: a, tx: ax, ty: ay + 1, dir: 'down', exit: 'down' });
  }
  return out;
}

