export interface TrainerDef {
  id: string;
  className: string;
  name: string;
  team: [string, number][];
  prize: number;
  intro: string;
  /** 배틀에서 졌을 때 대사 */
  lose: string;
  /** 이긴 뒤 말을 걸면 */
  after: string;
  /** 이긴 직후 실행할 스크립트 */
  afterScript?: string;
}

export interface NpcDef {
  id: string;
  x: number;
  y: number;
  dir?: Dir;
  sprite: { base: CharBase; pal: CharPalName } | { mon: string } | 'item';
  move?: 'still' | 'wander' | 'look';
  text?: string;
  script?: string;
  trainer?: TrainerDef;
  sight?: number;
  item?: ItemId;
  /** 이 플래그가 켜져 있으면 숨김 */
  hideIf?: string;
  /** 이 플래그가 켜져 있어야 보임 */
  showIf?: string;
  /** 물 위에서 헤엄치는 사람 (튜브를 끼고 윗몸만 보인다) */
  swim?: boolean;
}

export interface Warp {
  x: number;
  y: number;
  to: string;
  tx: number;
  ty: number;
  dir: Dir;
  /** 이 방향으로 걸으려 할 때 이동 (실내 매트). 없으면 밟는 순간 이동 (문) */
  exit?: Dir;
}

export interface Encounter { species: string; min: number; max: number; weight: number }
export type TimeOfDay = 'morning' | 'day' | 'night';

export interface MapDef {
  id: string;
  name: string;
  tiles: string[];
  outdoor?: boolean;
  border?: string;
  connections?: Partial<Record<'north' | 'south' | 'east' | 'west', { map: string; offset: number }>>;
  warps: Warp[];
  npcs: NpcDef[];
  signs?: { x: number; y: number; text: string }[];
  /** 밟으면 실행되는 스크립트 */
  triggers?: { x: number; y: number; script: string }[];
  /** surf: 파도타기 중에 물 위에서 나오는 포켓몬 */
  encounters?: { rate: number; surf?: Encounter[] } & Partial<Record<TimeOfDay, Encounter[]>>;
  /** 낚시로 낚이는 포켓몬 (물이 있는 맵, 없으면 민물) */
  fish?: FishSpot;
  /** 배경음악 (없으면 장소 종류로 정한다) */
  music?: string;
  /** 회복센터처럼 기절 후 돌아올 위치 */
  healSpot?: { x: number; y: number };
}

const enc = (species: string, min: number, max: number, weight: number): Encounter => ({ species, min, max, weight });

