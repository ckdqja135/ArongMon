/** 느티 박사: 잡은 포켓몬 수로 도감을 평가한다 */
export function profRating(caught: number) {
  if (caught < 10) return '이제 막 시작이구나!\n풀숲에서 여러 포켓몬을 만나 보렴.';
  if (caught < 20) return '조금씩 모이고 있구나.\n볼을 넉넉히 챙겨 다니렴.';
  if (caught < 40) return '꽤 잘하고 있구나! 낚시를 하면\n물 포켓몬도 만날 수 있단다.';
  if (caught < 80) return '대단하구나! 진화의 돌로만\n진화하는 포켓몬도 있단다.';
  if (caught < 120) return '놀라워! 키우미집에 맡기면\n알을 얻을 수도 있단다.';
  if (caught < 151) return '거의 다 왔구나! 남은 포켓몬은\n정말 귀한 녀석들일 거야.';
  return '151마리를 모두 모으다니!\n너와 아롱이는 진정한 박사로구나!';
}
