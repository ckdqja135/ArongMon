/** 아직 못 받은 배지: 색을 빼고 어둡게 (모양만 보인다) */
export function dimPalette(pal: Palette): Palette {
  return pal.map((hex, i) => {
    if (i === 1) return '#14141c';
    const v = parseInt(hex.slice(1), 16);
    const l = ((v >> 16) & 255) * 0.3 + ((v >> 8) & 255) * 0.59 + (v & 255) * 0.11;
    const g = Math.round(40 + l * 0.22).toString(16).padStart(2, '0');
    return `#${g}${g}${g}`;
  });
}
