/** frame: 0 = 서 있음, 1 = 걸음 A, 2 = 걸음 B (앞뒤 모습은 A를 좌우로 뒤집은 것) */
export function charFrame(base: CharBase, dir: Dir, frame: 0 | 1 | 2): Grid {
  const view: View = dir === 'right' ? 'left' : dir;
  const body = BODIES[base][view][frame === 0 ? 0 : 1];
  const g = parseArt([...HEADS[base][view], ...body].join('\n'), 'char');
  if (view === 'left') return dir === 'right' ? flipH(g) : g;
  if (frame !== 2) return g;
  // 머리는 그대로 두고 몸만 뒤집는다
  return g.map((r, y) => (y < 10 ? r : [...r].reverse()));
}

