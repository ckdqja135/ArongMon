export const hasFieldArt = (species: string) => species in FIELD;

/** frame: 0 = 서 있음, 1 = 걸음 A, 2 = 걸음 B */
export function arongFieldFrame(species: string, dir: Dir, frame: 0 | 1 | 2): Grid {
  const view: View = dir === 'right' ? 'left' : dir;
  const sheet = FIELD[species][view];
  // 옆모습은 [다리 모음, 다리 벌림]을 번갈아, 앞뒤 모습은 한쪽 발을 번갈아 든다
  const stepping = view === 'left' ? frame === 1 : frame !== 0;
  const rows = stepping ? [...sheet.rows.slice(0, 14), ...sheet.step] : sheet.rows;
  const g = parseArt(rows.join('\n'), `${species}:${view}`);
  if (view === 'left') return dir === 'right' ? flipH(g) : g;
  return frame === 2 ? g.map((r, y) => (y < 14 ? r : [...r].reverse())) : g;
}
