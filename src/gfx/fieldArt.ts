// ── 건물 ──
// 지붕 (0 빛, 1 밝음, 2 바탕, 3 외곽선, 4 그늘, 5 깊은 그늘). 기와가 4줄씩 엇갈려 쌓인다
export type RoofPart = 'tl' | 't' | 'tr' | 'bl' | 'b' | 'br';
export function roofGrid(part: RoofPart): Grid {
  const top = part[0] === 't', bottom = part[0] === 'b';
  const left = part.endsWith('l'), right = part.endsWith('r');
  return Array.from({ length: 16 }, (_, y) =>
    Array.from({ length: 16 }, (_, x) => {
      if (left && x === 0) return 3;
      if (right && x === 15) return 3;
      if (top && y === 0) return 3;
      if (top && y === 1) return 0;
      if (bottom && y >= 12) return y === 15 ? 3 : y === 12 ? 4 : 5;
      if (left && x === 1) return 1;
      if (right && x === 14) return 4;
      // 위 지붕 타일은 마루 아래부터 기와가 시작된다
      const yy = top ? y + 2 : y;
      const band = Math.floor(yy / 4);
      const row = yy % 4;
      if (row === 0) return 1;
      if (row === 3) return 4;
      return (x + (band % 2) * 4) % 8 === 0 ? 4 : 2;
    }),
  );
}

// 벽 (0 흰색, 1 밝음, 2 바탕, 3 외곽선, 4 그늘, 5 깊은 그늘, 6 밝은 유리, 7 유리, 8 나무문, 9 나무문 그늘)
export type WallPart = 'l' | 'm' | 'r';
export function wallGrid(part: WallPart): Grid {
  return Array.from({ length: 16 }, (_, y) =>
    Array.from({ length: 16 }, (_, x) => {
      if (part === 'l' && x === 0) return 3;
      if (part === 'r' && x === 15) return 3;
      if (y === 0) return 5;
      if (y === 1) return 4;
      if (y === 15) return 3;
      if (y === 14) return 5;
      if (part === 'l' && x === 1) return 1;
      if (part === 'r' && x === 14) return 4;
      return y % 4 === 3 ? 4 : 2;
    }),
  );
}

