/** 등대 몸통: 빨강·흰색 가로 줄무늬. side: 'l' 왼쪽, 'm' 가운데, 'r' 오른쪽 */
export function lighthouseGrid(side: 'l' | 'm' | 'r'): Grid {
  return Array.from({ length: 16 }, (_, y) =>
    Array.from({ length: 16 }, (_, x) => {
      if (side === 'l' && x < 3) return -1;
      if (side === 'r' && x > 12) return -1;
      if ((side === 'l' && x === 3) || (side === 'r' && x === 12)) return 3;
      const red = Math.floor(y / 4) % 2 === 1;
      const shade = side === 'r' && x > 9 ? 1 : 0;
      if (red) return shade ? 6 : 2;
      return shade ? 1 : side === 'l' && x === 4 ? 0 : 0;
    }),
  );
}

