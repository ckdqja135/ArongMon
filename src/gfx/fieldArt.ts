// 바깥 필드 타일 (DS 다이아몬드/펄 느낌). 색을 4개보다 많이 쓰고, 이웃 칸에 따라 모양이 바뀐다.
// 각 그림의 숫자는 palettes.ts의 같은 이름 팔레트 번호. '.'은 투명 (아래 바닥 타일이 보인다).
import { flipH, parseArt, type Grid } from './pixel';

const A = (s: string, name: string) => parseArt(s, name);

const flipV = (g: Grid): Grid => [...g].reverse().map((r) => [...r]);
/** 시계 방향 90도 */
const rotate = (g: Grid): Grid => g[0].map((_, x) => g.map((r) => r[x]).reverse());
const shiftX = (g: Grid, n: number): Grid => g.map((r) => r.map((_, x) => r[(x - n + r.length) % r.length]));
/** 투명이 아닌 칸만 덮어 그린다 */
const over = (g: Grid, top: Grid): Grid => g.map((r, y) => r.map((c, x) => (top[y][x] >= 0 ? top[y][x] : c)));

