// 체육관 바닥: 반질반질한 큰 타일 (gymFloor: 0 빛, 1 밝은 칸, 2 어두운 칸, 3 줄눈, 4 반사)
export const GYM_FLOOR = make((x, y) => {
  if (x === 0 || y === 0) return 3;
  const dark = ((x >> 3) + (y >> 3)) & 1;
  if (x % 8 === 0 || y % 8 === 0) return 4;
  if (x % 8 === 1 && y % 8 === 1) return 0;
  return dark ? 2 : 1;
});

// 벽지 (wallIn: 0 흰색, 1 바탕, 2 줄무늬, 3 외곽선, 4 그늘, 5 걸레받이)
export const WALL_IN = make((x, y) => {
  if (y === 0 || y === 15) return 3;
  if (y === 1) return 4;
  if (y === 11) return 0;
  if (y === 12) return 4;
  if (y >= 13) return 5;
  return x % 4 === 0 ? 2 : (x + y) % 8 === 2 && y % 3 === 0 ? 0 : 1;
});

