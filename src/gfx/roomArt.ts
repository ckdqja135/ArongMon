// ── 동굴 (cave: 0 빛, 1 밝은 흙, 2 바탕, 3 진한 그늘, 4 중간 그늘, 5 깊은 그늘) ──
export const CAVE_FLOOR = make((x, y) => {
  const n = noise(x, y);
  if (n < 0.04) return 1;
  if (n < 0.1) return 4;
  // 작은 돌: 위는 밝게, 아래는 그늘
  const m = noise(x >> 2, y >> 2);
  if (m > 0.86 && (x & 3) === 1 && (y & 3) === 1) return 0;
  if (m > 0.86 && (x & 3) === 1 && (y & 3) === 2) return 4;
  return 2;
});

/** 동굴 벽. 1: 아래가 바닥 (바위 단면이 보인다), 2: 위가 바닥 (윗면 가장자리) */
export function caveWallGrid(v: number): Grid {
  return make((x, y) => {
    if (v & 2 && y === 0) return 3;
    if (v & 2 && y === 1) return 4;
    if (v & 1 && y >= 6) {
      if (y === 15) return 3;
      if (y === 14) return 5;
      if (y === 6) return 1;
      const band = (y - 7) % 3;
      if (band === 0) return noise(x, y) < 0.3 ? 5 : 4;
      return (x + Math.floor((y - 7) / 3) * 5) % 9 === 0 ? 4 : 2;
    }
    const n = noise(x + 7, y + 3);
    if (n < 0.08) return 3;
    if (n < 0.3) return 4;
    return 5;
  });
}

// ── 불탄 탑 (burnt: 0 재 빛, 1 밝은 숯, 2 숯, 3 외곽선, 4 중간 재, 5 흩어진 재) ──
/** 마루가 그을린 바닥 (마루 무늬에 재가 흩어져 있다) */
export const BURNT_FLOOR = make((x, y) => (noise(x + 3, y + 11) < 0.07 ? 5 : FLOOR[y][x]));

/** 타다 남은 나무 기둥 (붙여 세우면 벽이 된다) */
export const PILLAR = make((x, y) => {
  if (x < 3 || x > 12) return 3;
  if (x === 3 || x === 12) return 3;
  if (x === 4) return 1;
  if (x === 11) return 4;
  if (y % 5 === 2 && x > 5 && x < 10) return 3;
  return x === 7 ? 4 : 2;
});

/** 바닥에 뚫린 구멍과 사다리 */
export const LADDER = make((x, y) => {
  if (x < 2 || x > 13 || y < 2 || y > 13) return BURNT_FLOOR[y][x];
  if (y === 2) return 4;
  if (x === 5 || x === 10) return 1;
  if (y % 3 === 0 && x > 5 && x < 10) return 1;
  return 3;
});

// ── 고스트 체육관 (ghostFloor: 0 빛, 1 밝은 칸, 2 어두운 칸, 3 줄눈, 4 반사) ──
export const GHOST_FLOOR = make((x, y) => {
  if (x === 0 || y === 0) return 3;
  if (x % 8 === 0 || y % 8 === 0) return 4;
  if (x % 8 === 1 && y % 8 === 1) return 0;
  return ((x >> 3) + (y >> 3)) & 1 ? 2 : 1;
});

