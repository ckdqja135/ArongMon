/** 위층으로 가는 계단 (wood: 0 빛, 1 밝은 나무, 2 나무, 3 외곽선, 4 그늘, 5 깊은 그늘) */
export const STAIRS = make((x, y) => {
  if (x === 0 || x === 15) return 3;
  const step = Math.floor(y / 4);
  const row = y % 4;
  if (row === 0) return 0;
  if (row === 3) return 4 + (step === 3 ? 1 : 0);
  return x === 1 ? 4 : 1;
});

// ── 로켓단 아지트 철판 바닥 (metal: 0 리벳 빛, 1 밝음, 2 바탕, 3 외곽선, 4 이음매) ──
export const METAL_FLOOR = make((x, y) => {
  if (x % 8 === 0 || y % 8 === 0) return 4;
  if (x % 8 === 7 || y % 8 === 7) return 3;
  if ((x % 8 === 2 || x % 8 === 5) && (y % 8 === 2 || y % 8 === 5)) return 0;
  if (y % 8 === 1) return 1;
  return 2;
});

// ── 얼음 체육관 바닥 (ice: 0 반짝임, 1 바탕, 2 그늘, 3 금, 4 중간) ──
export const ICE_FLOOR = make((x, y) => {
  const d = (x + y) % 16;
  if (d === 3 || d === 4) return 0;
  if (d === 10) return 4;
  if (noise(x + 5, y + 9) < 0.04) return 3;
  return y > 12 ? 2 : 1;
});
